// Map iteration count to a simple RGB color
void get_color(int iter, uint8_t *r, uint8_t *g, uint8_t *b)
{
	if (iter == MAX_ITER) {
		*r = *g = *b = 0; // Black for points inside the set
		return;
	}
	// Access Color RAM at address 'iter'
	*r = magma_palette[iter][0];
	*g = magma_palette[iter][1];
	*b = magma_palette[iter][2];
}

int main(void)
{
	// Define the complex plane window
	float x_min = -2.0, x_max = 1.0;
	float y_min = -1.2, y_max = 1.2;

	FILE *fp = fopen("mandelbrot.ppm", "wb");
	fprintf(fp, "P6\n%d %d\n255\n", WIDTH, HEIGHT);

	for (int y = 0; y < HEIGHT; y++) {
		for (int x = 0; x < WIDTH; x++) {
			// Map pixel to complex coordinate C
			float cx_f = x_min + (x / (float)WIDTH) * (x_max - x_min);
			float cy_f = y_min + (y / (float)HEIGHT) * (y_max - y_min);
			int32_t cr = float_to_fp(cx_f);
			int32_t ci = float_to_fp(cy_f);

			size_t iter = mandelbrot_fixed(cr, ci);
			uint8_t r, g, b;
			get_color(iter, &r, &g, &b);
			fputc(r, fp);
			fputc(g, fp);
			fputc(b, fp);
		}
	}

	fclose(fp);
	printf("Done! Open mandelbrot.ppm to see the result.\n");
	return 0;
}
